"""Parse erp_schema.dsl, validate it, emit PostgreSQL DDL and Mermaid ER diagrams (crow's foot).

python gen_ddl.py            # validates, writes sql/01_ddl.sql and diagrams/*.mmd"""

import re
import sys
from collections import OrderedDict


def parse(path=None):
    import os

    path = path or os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "erp_schema.dsl"
    )
    T = OrderedDict()
    cur = None
    for ln in open(path):
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        if ln.startswith("table "):
            head, _, purpose = ln[6:].partition("|")
            s, n = head.strip().split(".")
            cur = dict(schema=s, name=n, purpose=purpose.strip(), cols=[])
            T[f"{s}.{n}"] = cur
        else:
            p = ln.split()
            c = dict(
                name=p[0],
                type=p[1],
                pk=False,
                uniq=False,
                null=False,
                sens=False,
                fk=None,
            )
            for f in p[2:]:
                if f in ("pk", "uniq", "null", "sens"):
                    c[f] = True
                elif f.startswith("fk:"):
                    c["fk"] = f[3:]
                else:
                    raise ValueError(f"{cur['name']}.{p[0]}: bad flag {f}")
            cur["cols"].append(c)
    return T


def pk(t):
    return next(c for c in t["cols"] if c["pk"])


def norm(ty):
    return {"serial": "int", "bigserial": "bigint"}.get(ty, ty)


def validate(T):
    errs = []
    names = {}
    for k, t in T.items():
        if t["name"] in names:
            errs.append(f"duplicate table name {t['name']}")
        names[t["name"]] = k
        if not any(c["pk"] for c in t["cols"]):
            errs.append(f"{k}: no pk")
        seen = set()
        for c in t["cols"]:
            if c["name"] in seen:
                errs.append(f"{k}: dup col {c['name']}")
            seen.add(c["name"])
    for k, t in T.items():
        for c in t["cols"]:
            if not c["fk"]:
                continue
            parts = c["fk"].split(".")
            tk = ".".join(parts[:2])
            col = parts[2] if len(parts) > 2 else None
            if tk not in T:
                errs.append(f"{k}.{c['name']} -> missing table {tk}")
                continue
            tc = (
                next((x for x in T[tk]["cols"] if x["name"] == col), None)
                if col
                else pk(T[tk])
            )
            if not tc:
                errs.append(f"{k}.{c['name']} -> missing col {c['fk']}")
                continue
            if norm(tc["type"]) != norm(c["type"]):
                errs.append(
                    f"{k}.{c['name']} {c['type']} vs {tk}.{tc['name']} {tc['type']}"
                )
    return errs


def mer_type(t):
    return re.sub(r"[^A-Za-z0-9_]", "", t.split("(")[0])


def mermaid(T, schemas=None, cross=False, overview=False):
    sel = {k for k, t in T.items() if schemas is None or t["schema"] in schemas}
    out = ["erDiagram"]
    rel = []
    shown = set(sel)
    for k in sel:
        for c in T[k]["cols"]:
            if not c["fk"]:
                continue
            tk = ".".join(c["fk"].split(".")[:2])
            if tk in sel or (cross and not overview):
                if tk not in sel:
                    shown.add(tk)
                card = "|o" if c["null"] else "||"
                one = "o|" if c["null"] else "||"
                right = "o|" if c["uniq"] or c["pk"] else "o{"
                rel.append(
                    f'  {T[tk]["name"]} {"||" if not c["null"] else "o|"}--{right} {T[k]["name"]} : "{c["name"]}"'
                )
    for k in shown:
        t = T[k]
        if overview:
            out.append(f'  {t["name"]} {{ }}')
            continue
        out.append(f'  {t["name"]} {{')
        for c in t["cols"]:
            if k not in sel and not c["pk"]:
                continue
            tag = (
                "PK" if c["pk"] else ("FK" if c["fk"] else ("UK" if c["uniq"] else ""))
            )
            out.append(f'    {mer_type(c["type"])} {c["name"]} {tag}'.rstrip())
        out.append("  }")
    return "\n".join(out + sorted(set(rel)))


SCHEMAS = ["auth", "org", "people", "acad", "fin", "lib", "svc", "gh", "cdc", "sys"]


def ddl(T):
    out = ["-- GENERATED by gen_ddl.py from erp_schema.dsl. Do not edit by hand.", ""]
    for s in SCHEMAS:
        out.append(f"CREATE SCHEMA {s};")
    out.append("")
    fks, idx = [], []
    for k, t in T.items():
        cols, pks = [], [c["name"] for c in t["cols"] if c["pk"]]
        for c in t["cols"]:
            line = f'  {c["name"]} {c["type"]}'
            if len(pks) == 1 and c["pk"]:
                line += " PRIMARY KEY"
            else:
                if not c["null"] and not c["pk"]:
                    line += " NOT NULL"
                if c["uniq"]:
                    line += " UNIQUE"
            cols.append(line)
            if c["fk"]:
                parts = c["fk"].split(".")
                tk = ".".join(parts[:2])
                tc = parts[2] if len(parts) > 2 else pk(T[tk])["name"]
                fks.append(
                    f'ALTER TABLE {k} ADD FOREIGN KEY ({c["name"]}) REFERENCES {tk}({tc});'
                )
                if not c["pk"] and not c["uniq"]:
                    idx.append(f'CREATE INDEX ON {k}({c["name"]});')
        if len(pks) > 1:
            cols.append(f'  PRIMARY KEY ({", ".join(pks)})')
        out.append(f"CREATE TABLE {k} (\n" + ",\n".join(cols) + "\n);")
        out.append(
            f"COMMENT ON TABLE {k} IS '{t['purpose'].replace(chr(39), chr(39)*2)}';"
        )
        out.append("")
    out.append(
        "-- foreign keys are added after all tables exist (the model has circular references)"
    )
    out += fks + [""] + idx
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    import os

    here = os.path.dirname(os.path.abspath(__file__))
    T = parse()
    errs = validate(T)
    if errs:
        sys.exit("\n".join(errs))
    open(os.path.join(here, "sql", "01_ddl.sql"), "w").write(ddl(T))
    os.makedirs(os.path.join(here, "diagrams"), exist_ok=True)
    for s in SCHEMAS:
        open(os.path.join(here, "diagrams", f"{s}.mmd"), "w").write(
            mermaid(T, [s], cross=True)
        )
    open(os.path.join(here, "diagrams", "overview.mmd"), "w").write(
        mermaid(T, None, overview=True)
    )
    print(len(T), "tables valid; wrote sql/01_ddl.sql and diagrams/*.mmd")
